import { writeFileSync } from 'node:fs';
import { test } from 'vitest';
import { simulateAll, type SimSummary } from '../src/games/brazil/sim';

/**
 * Balance report of the Brazilian games: `npm run sim:brazil` → docs/brazil-balance.md.
 * Sizes: N_MANILHA, N_PIFE, N_VIDEO, N_CANASTRA (rounds per strategy).
 */
const n = {
  manilha: Number(process.env.N_MANILHA ?? 40000),
  pife: Number(process.env.N_PIFE ?? 1500),
  video: Number(process.env.N_VIDEO ?? 2000),
  canastra: Number(process.env.N_CANASTRA ?? 20000),
};
const pct = (x: number) => `${(100 * x).toFixed(2)}%`;

test('brazilian games balance report', () => {
  const t0 = performance.now();
  const all = simulateAll(n);
  const out: string[] = ['# Brazilian card games — balance simulation', ''];
  out.push('Real round classes, evaluators, dealer policies and settlement; base bet 10; seed 2026 (reproducible). RTP = chips returned ÷ chips bet. The ± is a 95% confidence interval. Strategies are reference players, not proven optimal play.', '');
  const modes = [...new Set(all.map((s) => s.mode))];
  for (const m of modes) {
    const rows = all.filter((s) => s.mode === m);
    out.push(`## ${m}`, '', `${rows[0].rounds} rounds per strategy.`, '');
    out.push('| Strategy | Win | Loss | Push | Fold | Avg bet | Avg return | Net / round | RTP | House edge | SD |', '|---|---|---|---|---|---|---|---|---|---|---|');
    for (const s of rows)
      out.push(
        `| ${s.strategy} | ${pct(s.win / s.rounds)} | ${pct(s.loss / s.rounds)} | ${pct(s.push / s.rounds)} | ${pct(s.fold / s.rounds)} | ${s.avgBet.toFixed(2)} | ${s.avgReturn.toFixed(3)} | ${s.netPerRound >= 0 ? '+' : ''}${s.netPerRound.toFixed(3)} | ${(100 * s.rtp).toFixed(2)}% ± ${(100 * s.rtpCi).toFixed(2)} | ${pct(1 - s.rtp)} | ${s.sd.toFixed(2)} |`,
      );
    const withCls = rows.filter((s) => Object.keys(s.classes).length);
    if (withCls.length) {
      const keys = [...new Set(withCls.flatMap((s) => Object.keys(s.classes)))].sort();
      out.push('', "Final class of the player's hand:", '', `| Strategy | ${keys.join(' | ')} |`, `|---|${keys.map(() => '---').join('|')}|`);
      for (const s of withCls) out.push(`| ${s.strategy} | ${keys.map((k) => pct((s.classes[k] ?? 0) / s.rounds)).join(' | ')} |`);
    }
    out.push('', 'Payout distribution (total return in base bets → share of rounds):', '');
    for (const s of rows) out.push(`- ${s.strategy}: ${Object.entries(s.payouts).sort((a, b) => Number(a[0]) - Number(b[0])).map(([k, v]) => `${k}× ${pct(v / s.rounds)}`).join(', ')}`);
    out.push('');
  }
  out.push(`_Generated by sim/brazil.sim.ts in ${((performance.now() - t0) / 1000).toFixed(0)} s._`, '');
  writeFileSync('docs/brazil-balance.md', out.join('\n'));
  console.log(out.join('\n'));
  void (null as unknown as SimSummary);
});
