import { writeFileSync } from 'node:fs';
import { test } from 'vitest';
import { seededRng } from '../src/core/rng';
import { ABYSS, type ProfileId } from '../src/games/abyss/config';
import { simulate, type SimStats, type SkillPolicy } from '../src/games/abyss/sim';
import { SKILLS } from '../src/games/abyss/skills';

/**
 * Abyss Poker balance report: `npm run sim:abyss` (N hands per line, default 2000).
 * Every line uses the same seeds; writes docs/abyss-balance.md.
 */
const N = Number(process.env.N ?? 2000);
const cfg = { dealerSamples: 200 };
const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
const sg = (x: number) => `${x >= 0 ? '+' : ''}${x.toFixed(3)}`;

function run(policy: SkillPolicy, profile?: ProfileId): SimStats {
  return simulate({ hands: N, policy, rng: seededRng(11), aiRng: seededRng(22), botRng: seededRng(33), ante: 20, profile, cfg, botSamples: 120 });
}

test('abyss balance report', () => {
  const t0 = performance.now();
  const out: string[] = ['# Abyss Poker — balance simulation', ''];
  out.push(`${N} hands per line, Ante 20 (budget 200), dealer profile drawn at random unless stated. The player bot plays a balanced equity strategy and uses everything its skills reveal. Results in Antes per hand; skill costs included.`, '');
  const base = run({ kind: 'none' });
  const H = '| Policy | Net / hand | Win | Dealer folds | Player folds | Showdown | Skill spend / hand | Δ vs no skills | Δ per chip spent | Budget used |\n|---|---|---|---|---|---|---|---|---|---|';
  const line = (name: string, s: SimStats) => {
    const spend = s.skillSpend / s.hands / 20;
    const delta = s.netPerHand - base.netPerHand;
    const perChip = spend > 0 ? (delta / spend).toFixed(2) : '—';
    return `| ${name} | ${sg(s.netPerHand)} | ${pct((s.wins + s.dealerFolds) / s.hands)} | ${pct(s.dealerFolds / s.hands)} | ${pct(s.playerFolds / s.hands)} | ${pct(s.showdowns / s.hands)} | ${spend.toFixed(3)} | ${sg(delta)} | ${perChip} | ${pct(s.budgetUse)} |`;
  };
  out.push('## 1. Skills: one skill bought whenever it can be', '', H, line('No skills', base));
  const all: SimStats[] = [base];
  for (const s of SKILLS) {
    const r = run({ kind: 'single', id: s.id });
    all.push(r);
    out.push(line(`${s.id} (Tier ${s.tier})`, r));
  }
  out.push('', '## 2. Heavy use and abusive combinations', '', H);
  const heavy: [string, SkillPolicy][] = [
    ['Cheapest skill every street', { kind: 'all' }],
    ["Make 'Em Chase + all-in with equity > 75%", { kind: 'chaseValue' }],
    ['Pressure + bluff bet with equity < 35%', { kind: 'pressureBluff' }],
    ['Peek + all-in with equity > 72%', { kind: 'peekShove' }],
  ];
  let every: SimStats | null = null;
  for (const [name, p] of heavy) {
    const r = run(p);
    all.push(r);
    if (p.kind === 'all') every = r;
    out.push(line(name, r));
  }
  out.push('', '## 3. Skill use and price paid by street (cheapest skill every street)', '', '| Skill | Uses / hand |', '|---|---|');
  for (const s of SKILLS) out.push(`| ${s.id} | ${(every!.skillUses[s.id] / every!.hands).toFixed(3)} |`);
  out.push('', '| Street | Spend / hand (Antes) |', '|---|---|');
  for (const k of ['PRE_FLOP', 'FLOP', 'TURN', 'RIVER'] as const) out.push(`| ${k} | ${(every!.spendByStreet[k] / every!.hands / 20).toFixed(3)} |`);
  out.push('', '## 4. Dealer profiles (no skills)', '', H);
  for (const p of Object.keys(ABYSS.profiles) as ProfileId[]) {
    const r = run({ kind: 'none' }, p);
    all.push(r);
    out.push(line(p, r));
  }
  out.push('', '## 5. Financial consistency', '', `Wallet change equals the settled net result in every simulated hand: **${all.every((s) => s.consistent) ? 'yes' : 'NO'}**.`, '');
  out.push(`_Generated by sim/abyss.sim.ts in ${((performance.now() - t0) / 1000).toFixed(0)} s._`, '');
  writeFileSync('docs/abyss-balance.md', out.join('\n'));
  console.log(out.join('\n'));
});
