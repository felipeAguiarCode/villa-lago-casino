import { writeFileSync } from 'node:fs';
import { test } from 'vitest';
import { seededRng } from '../src/core/rng';
import { alwaysCheck, alwaysDouble, CAT_LABEL, simulate, thresholdPolicy, type BetPolicy, type SimResult } from '../src/games/showdown/sim';
import { heuristicStrategy, highCardStrategy, monteCarloStrategy, randomStrategy, type PickStrategy } from '../src/games/showdown/strategy';

/**
 * Showdown Poker balance report: `npm run sim:showdown` (N rounds per line, default 4000).
 * Every line replays the same deals (same deck and dealer seeds), so differences come from the
 * strategy being compared, not from luck. Writes docs/showdown-balance.md.
 */
const N = Number(process.env.N ?? 4000);
const S = Number(process.env.S ?? 100);
const pct = (x: number) => `${(100 * x).toFixed(2)}%`;
const sgn = (x: number) => `${x >= 0 ? '+' : ''}${(100 * x).toFixed(2)}%`;

function run(player: () => PickStrategy, bet: () => BetPolicy = () => alwaysCheck): SimResult {
  return simulate({ rounds: N, player: player(), dealer: monteCarloStrategy(seededRng(202), S), bet: bet(), rng: seededRng(101) });
}

const row = (name: string, r: SimResult) =>
  `| ${name} | ${pct(r.wins / r.rounds)} | ${pct(r.losses / r.rounds)} | ${pct(r.pushes / r.rounds)} | ${pct(r.folds / r.rounds)} | ${pct(r.doubles[0] / r.rounds)} / ${pct(r.doubles[1] / r.rounds)} | ${(r.rtp * 100).toFixed(2)}% | ${sgn(r.perAnte)} |`;
const HEAD = '| Strategy | Win | Loss | Push | Fold | Double 1st / 2nd | Return per chip bet | Player result per ante |\n|---|---|---|---|---|---|---|---|';

test('showdown balance report', () => {
  const t0 = performance.now();
  const out: string[] = [];
  out.push('# Showdown Poker — balance simulation', '');
  out.push(`${N} rounds per line against the Monte Carlo dealer (${S} samples per decision). Ante 10, win pays 1:1 on the total bet, ties push. Same deals on every line.`, '');

  out.push('## 1. Card-selection strategies (player always checks)', '', HEAD);
  const mc = () => monteCarloStrategy(seededRng(303), S);
  const sel: [string, () => PickStrategy][] = [
    ['Random', () => randomStrategy(seededRng(404))],
    ['Always the highest card', () => highCardStrategy()],
    ['Simple heuristic (pairs, suits, connectors)', () => heuristicStrategy()],
    ['Monte Carlo (same as the dealer)', mc],
  ];
  let mcCheck: SimResult | null = null;
  for (const [name, p] of sel) {
    const r = run(p);
    if (name.startsWith('Monte')) mcCheck = r;
    out.push(row(name, r));
  }

  out.push('', '## 2. Final hand frequencies (Monte Carlo vs Monte Carlo)', '', '| Hand | Player | Dealer |', '|---|---|---|');
  const r0 = mcCheck!;
  const shown = r0.playerCats.reduce((a, b) => a + b, 0);
  for (let c = 9; c >= 0; c--) out.push(`| ${CAT_LABEL[c as 0]} | ${pct(r0.playerCats[c] / shown)} | ${pct(r0.dealerCats[c] / shown)} |`);

  out.push('', '## 3. Betting decisions (Monte Carlo selection)', '', HEAD);
  out.push(row('Always check', r0));
  out.push(row('Always double', run(mc, () => alwaysDouble)));
  for (const th of [0.5, 0.55, 0.6, 0.65, 0.7]) out.push(row(`Double when strength ≥ ${th}`, run(mc, () => thresholdPolicy(seededRng(505), [th, th], null, 80))));
  out.push(row('Double ≥ 0.62 / 0.60 (hint lamp)', run(mc, () => thresholdPolicy(seededRng(505), [0.62, 0.6], null, 80))));
  for (const fb of [0.2, 0.3, 0.4]) out.push(row(`Hint lamp + fold below ${fb}`, run(mc, () => thresholdPolicy(seededRng(505), [0.62, 0.6], [fb, fb], 80))));

  out.push('', `_Generated by sim/showdown.sim.ts in ${((performance.now() - t0) / 1000).toFixed(0)} s._`, '');
  writeFileSync('docs/showdown-balance.md', out.join('\n'));
  console.log(out.join('\n'));
});
